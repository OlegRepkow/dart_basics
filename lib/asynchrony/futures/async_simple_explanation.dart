// Future та async/await - просте пояснення
//
// Future<T> - це обіцянка, що значення типу T зʼявиться колись у майбутньому
// (наприклад, після запиту на сервер або затримки).
//
// async - позначає функцію як асинхронну; така функція завжди повертає Future.
// await - призупиняє виконання async-функції, доки Future не завершиться,
//         і повертає його результат. Основний потік при цьому не блокується.

void main() async {
  print('1. Запитуємо дані з сервера...');

  // await чекає на результат Future, не блокуючи програму.
  final data = await fetchData();
  print('2. Отримали: $data');

  // then - альтернатива await: виконати код, коли Future завершиться.
  fetchData().then((value) => print('3. Через then: $value'));

  print('4. Цей рядок виконується одразу, не чекаючи then');
}

// Асинхронна функція, що імітує отримання даних з сервера.
// Повертає Future<String>, бо результат буде готовий лише за 2 секунди.
Future<String> fetchData() async {
  await Future<void>.delayed(const Duration(seconds: 2));
  return 'Дані з сервера';
}
