// Математичні оператори у Dart

void main() {
  final a = 10;
  final b = 3.14159265359;

  // Основні арифметичні дії
  print('sum: ${a + b}');
  print('difference: ${a - b}');
  print('multiplication: ${a * b}');
  print('division: ${a / b}');

  print('-----------------------------------');

  // Різні види ділення
  print('Звичайне ділення: ${12 / 5}'); // 2.4
  print('Цілочисельне ділення: ${12 ~/ 5}'); // 2, тільки ціла частина
  print('Остача від ділення: ${12 % 5}'); // 2, бо 5 * 2 = 10, а 12 - 10 = 2

  print('-----------------------------------');

  // Округлення чисел
  final someMoney = 25.5;
  print('round (до найближчого): ${someMoney.round()}'); // 26
  print('ceil (вгору): ${someMoney.ceil()}'); // 26
  print('floor (вниз): ${someMoney.floor()}'); // 25
  print('toStringAsFixed(2): ${someMoney.toStringAsFixed(2)}'); // 25.50

  print('-----------------------------------');

  // Інкремент: збільшення значення на 1
  var counter = 10;
  counter++; // те саме, що counter = counter + 1
  print('counter після ++: $counter'); // 11

  // Різниця між постфіксною та префіксною формами:
  // i++ спочатку повертає старе значення, а потім збільшує
  // ++i спочатку збільшує, а потім повертає нове значення
  var i = 5;
  print('i++ повертає: ${i++}, тепер i = $i'); // повертає 5, i стає 6
  print('++i повертає: ${++i}, тепер i = $i'); // повертає 7, i стає 7
}
